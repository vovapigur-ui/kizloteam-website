#!/usr/bin/env node
// Regenerates everything that is derived from page content: the site chrome
// (skip link, header, footer, head fonts; see lib/chrome.mjs), JSON-LD,
// hreflang, the market-report pages and sitemap.xml.
//
// The site itself stays a plain static site with no deploy-time build. This
// script runs locally and its output is committed, so Render keeps serving
// files straight from the repo.
//
//   npm run build

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, statSync } from "node:fs";
import { join, dirname, relative, sep } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

import { syncChrome } from "./lib/chrome.mjs";
import { breadcrumbs, canonicalOf, faqs, reviews } from "./lib/extract.mjs";
import { escapeHtml, textOf } from "./lib/html.mjs";
import { parseFrontMatter, renderMarkdown, splitH1 } from "./lib/markdown.mjs";
import { loadPosts, postUrl, renderIndex, renderPost } from "./lib/reports.mjs";
import { agency, people, ANALYTICS, HREFLANG_CLUSTERS, NO_ANALYTICS, RATING, SITE, SKIP, VLAD_ID, AGENCY_ID } from "./lib/site-data.mjs";
import { breadcrumbNav, page } from "./lib/template.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const START = "  <!-- schema:start · generated by scripts/build.mjs · do not hand-edit -->";
const END = "  <!-- schema:end -->";
const HREF_START = "  <!-- hreflang:start · generated by scripts/build.mjs -->";
const HREF_END = "  <!-- hreflang:end -->";
const ANALYTICS_START = "  <!-- analytics:start · generated by scripts/build.mjs · do not hand-edit -->";
const ANALYTICS_END = "  <!-- analytics:end -->";

const log = [];

/* ------------------------------------------------------------------ pages */

function htmlFiles(dir = ROOT) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith(".") || entry === "node_modules" || entry === "scripts" || entry === "content") continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...htmlFiles(full));
    else if (entry.endsWith(".html")) out.push(relative(ROOT, full));
  }
  return out.sort();
}

/* --------------------------------------------------------- market reports */

function buildMarketReports(posts) {
  const published = posts.filter((p) => !p.draft);
  mkdirSync(join(ROOT, "market-reports"), { recursive: true });
  writeFileSync(join(ROOT, "market-reports", "index.html"), renderIndex(published));
  log.push(`market-reports: index with ${published.length} published post(s)`);

  for (const post of published) {
    const dir = join(ROOT, "market-reports", post.slug);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, "index.html"), renderPost(post, published));
    log.push(`market-reports: wrote /market-reports/${post.slug}/`);
  }
  for (const post of posts.filter((p) => p.draft)) {
    log.push(`market-reports: DRAFT held back, not published: ${post.file}`);
  }
  return published;
}

/* --------------------------------------------------------- legal pages */

const LEGAL_DIR = join(ROOT, "content", "legal");

function loadLegal() {
  if (!existsSync(LEGAL_DIR)) return [];
  return readdirSync(LEGAL_DIR)
    .filter((f) => f.endsWith(".md") && !f.startsWith("_") && f !== "README.md")
    .map((file) => {
      const { data, body } = parseFrontMatter(readFileSync(join(LEGAL_DIR, file), "utf8"));
      const slug = data.slug || file.replace(/\.md$/, "");
      for (const key of ["title", "description"]) {
        if (!data[key]) throw new Error(`content/legal/${file}: missing front matter ${key}`);
      }
      const { heading, body: rest } = splitH1(body);
      return {
        file,
        slug,
        draft: data.draft === true,
        title: data.title,
        heading: heading || data.title,
        description: data.description,
        eyebrow: data.eyebrow || "Legal",
        body: rest,
      };
    })
    .sort((a, b) => a.slug.localeCompare(b.slug));
}

function buildLegal(docs) {
  const published = docs.filter((d) => !d.draft);
  for (const doc of published) {
    const trail = [{ name: "Home", href: "/" }, { name: doc.heading }];
    const body = `${breadcrumbNav(trail)}

    <section class="page-hero">
      <div class="wrap">
        <h1>${escapeHtml(doc.heading)}</h1>
      </div>
    </section>

    <section class="section section--tight">
      <div class="wrap grid">
        <div class="longread prose">
        ${renderMarkdown(doc.body)}
        </div>
      </div>
    </section>`;

    // No CTA band: a sales pitch under a privacy policy reads badly, and these
    // pages exist to be read, not to convert.
    const dir = join(ROOT, doc.slug);
    mkdirSync(dir, { recursive: true });
    writeFileSync(
      join(dir, "index.html"),
      page({
        title: doc.title,
        description: doc.description,
        canonical: `${SITE}/${doc.slug}/`,
        body,
        cta: false,
      })
    );
    log.push(`legal: wrote /${doc.slug}/`);
  }
  for (const doc of docs.filter((d) => d.draft)) log.push(`legal: DRAFT held back: ${doc.file}`);
  return published;
}

/* ------------------------------------------------------------ json-ld */

function graphFor(file, html, posts) {
  const canonical = canonicalOf(html);
  const graph = [agency()];

  if (file === "about/index.html") graph.push(...people());

  if (file === "index.html") {
    graph.push({
      "@type": "WebSite",
      "@id": `${SITE}/#website`,
      url: `${SITE}/`,
      name: "The Kizlo Team",
      alternateName: ["The Kizlo Team - Realtors", "Kizlo Team"],
      publisher: { "@id": AGENCY_ID },
      inLanguage: ["en-US", "uk-UA"],
    });
  }

  const crumbs = breadcrumbs(html);
  if (crumbs && crumbs.length > 1) graph.push({ "@type": "BreadcrumbList", itemListElement: crumbs });

  const questions = faqs(html);
  if (questions.length) graph.push({ "@type": "FAQPage", mainEntity: questions });

  if (file === "reviews/index.html") {
    const found = reviews(html);
    if (found.length) {
      // Only this page carries the rating: it is the one page where the
      // reviews behind the number are on screen.
      graph[0].aggregateRating = { "@type": "AggregateRating", ...RATING };
      graph[0].review = found.map((r) => ({ ...r, itemReviewed: { "@id": AGENCY_ID } }));
      log.push(`reviews: ${found.length} Review nodes + AggregateRating ${RATING.ratingValue}/${RATING.reviewCount}`);
    }
  }

  const post = posts.find((p) => canonical === postUrl(p.slug));
  if (post) {
    // headline is the visible h1; the longer search title rides along.
    graph.push({
      "@type": "BlogPosting",
      "@id": `${postUrl(post.slug)}#post`,
      headline: post.headline,
      ...(post.title !== post.headline ? { alternativeHeadline: post.title } : {}),
      description: post.description,
      image: post.image,
      datePublished: post.date,
      dateModified: post.updated,
      author: { "@id": VLAD_ID },
      publisher: { "@id": AGENCY_ID },
      mainEntityOfPage: postUrl(post.slug),
      inLanguage: "en-US",
    });
    // The author, named on the page itself, not only by reference.
    graph.push(people().find((person) => person["@id"] === VLAD_ID));
  }

  return { "@context": "https://schema.org", "@graph": graph };
}

function replaceManaged(html, startMark, endMark, replacement) {
  const start = html.indexOf(startMark);
  const end = html.indexOf(endMark);
  if (start !== -1 && end !== -1) {
    return html.slice(0, start) + replacement + html.slice(end + endMark.length);
  }
  return null;
}

function injectSchema(html, graph) {
  const block = `${START}\n  <script type="application/ld+json">\n${JSON.stringify(graph, null, 2)}\n  </script>\n${END}`;

  const replaced = replaceManaged(html, START, END, block);
  if (replaced) return replaced;

  // First run: drop the hand-written blocks and take their place.
  const existing = [...html.matchAll(/[ \t]*<script type="application\/ld\+json">[\s\S]*?<\/script>\n?/gi)];
  if (existing.length) {
    let out = html;
    for (let i = existing.length - 1; i >= 0; i -= 1) {
      const m = existing[i];
      out = out.slice(0, m.index) + (i === 0 ? `${block}\n` : "") + out.slice(m.index + m[0].length);
    }
    return out;
  }
  // Function replacer: `block` carries page copy that can contain `$1`, `$$`
  // etc., which String.replace treats as substitution patterns in a string
  // replacement and silently mangles.
  return html.replace(/([ \t]*)<\/head>/i, (_m, indent) => `${block}\n${indent}</head>`);
}

function injectHreflang(file, html) {
  const cluster = HREFLANG_CLUSTERS.find((c) => c.pages.includes(file));
  if (!cluster) return html;
  const links = cluster.alternates
    .map((a) => `  <link rel="alternate" hreflang="${a.hreflang}" href="${a.href}">`)
    .join("\n");
  const block = `${HREF_START}\n${links}\n${HREF_END}`;

  const replaced = replaceManaged(html, HREF_START, HREF_END, block);
  if (replaced) return replaced;
  // Function replacer for the same reason as injectSchema: `block` must be
  // inserted verbatim, never interpreted as a substitution pattern.
  return html.replace(/([ \t]*)(<link rel="canonical"[^>]*>)/i, (_m, indent, link) => `${indent}${link}\n${block}`);
}

// Both queues exist from the first byte, so a phone tap or a lead sent before
// either tag arrives is kept and replayed when it loads (js/track.js only
// calls gtag and clarity). The tags themselves stay off the critical path:
// Clarity, the behaviour study tool, loads once the document is parsed; GA4
// waits for the load event and the web fonts, then an idle moment (at most
// 2s), or the first pointerdown, keydown or scroll, whichever comes first.
function injectAnalytics(html) {
  const block = `${ANALYTICS_START}
  <script>
    // Only the live domain reports. localhost, file previews and Render
    // preview URLs stay out of GA4 and Clarity so the numbers are visitors only.
    window.__kzLive = /(^|\\.)kizloteam\\.com$/.test(location.hostname);
    if (!window.__kzLive) window["ga-disable-${ANALYTICS.ga4}"] = true;
    window.dataLayer = window.dataLayer || [];
    function gtag(){dataLayer.push(arguments);}
    gtag("js", new Date());
    gtag("config", "${ANALYTICS.ga4}");
    if (window.__kzLive) (function (w, d) {
      w.clarity = w.clarity || function () { (w.clarity.q = w.clarity.q || []).push(arguments); };
      function add(src) { var s = d.createElement("script"); s.async = true; s.src = src; d.head.appendChild(s); }
      function clarity() { add("https://www.clarity.ms/tag/" + "${ANALYTICS.clarity}"); }
      if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", clarity, { once: true }); else clarity();
      var sent = false, cues = ["pointerdown", "keydown", "scroll"];
      function ga() {
        if (sent) return;
        sent = true;
        cues.forEach(function (c) { w.removeEventListener(c, ga, true); });
        add("https://www.googletagmanager.com/gtag/js?id=${ANALYTICS.ga4}");
      }
      cues.forEach(function (c) { w.addEventListener(c, ga, { capture: true, passive: true }); });
      // The web fonts can land after load, and the headline repaints (the LCP) when they
      // do, so the idle wait starts once they are in (or after 3s at most).
      function idle() {
        var fonts = d.fonts && d.fonts.ready ? d.fonts.ready : Promise.resolve();
        Promise.race([fonts, new Promise(function (r) { setTimeout(r, 3000); })]).then(function () {
          if (w.requestIdleCallback) w.requestIdleCallback(ga, { timeout: 2000 }); else setTimeout(ga, 200);
        });
      }
      if (d.readyState === "complete") idle(); else w.addEventListener("load", idle, { once: true });
    })(window, document);
  </script>
  <script src="/js/track.js" defer></script>
${ANALYTICS_END}`;

  const replaced = replaceManaged(html, ANALYTICS_START, ANALYTICS_END, block);
  if (replaced) return replaced;
  return html.replace(/<\/head>/i, () => `${block}\n</head>`);
}

// Keep the footer in step across every page. Two pages carry slightly
// different legal wording, so this edits in place rather than replacing the
// whole footer, which would rewrite copy nobody asked to change.
function ensureFooter(file, html) {
  let out = html;

  if (!out.includes('<a href="/market-reports/">Market Reports</a>')) {
    out = out.replace(
      /([ \t]*)<li><a href="\/reviews\/">Reviews<\/a><\/li>/,
      '$1<li><a href="/market-reports/">Market Reports</a></li>\n$1<li><a href="/reviews/">Reviews</a></li>'
    );
  }

  // The Ukrainian link is Ukrainian text inside an English page: without a
  // lang attribute a screen reader reads it with English phonetics (WCAG 3.1.2).
  out = out.replace(
    /<li><a href="\/ukrainian-realtor-orlando\/">Українською<\/a><\/li>/,
    '<li><a href="/ukrainian-realtor-orlando/" lang="uk">Українською</a></li>'
  );

  const LEGAL_LINKS =
    '<p class="footer-legal__links"><a href="/privacy-policy/">Privacy Policy</a> · <a href="/terms-of-use/">Terms of Use</a> · <a href="/accessibility/">Accessibility</a></p>';

  if (!out.includes('class="footer-legal__links"')) {
    out = out.replace(
      /([ \t]*)<div class="footer-legal">\n/,
      `$1<div class="footer-legal">\n$1  ${LEGAL_LINKS}\n`
    );
  }
  // 404 has its own stripped-down footer with a different wrapper.
  if (!out.includes('class="footer-legal__links"')) {
    out = out.replace(
      /([ \t]*)<div class="wrap footer-legal"([^>]*)>\n/,
      `$1<div class="wrap footer-legal"$2>\n$1  ${LEGAL_LINKS}\n`
    );
  }

  // The mark carries the words "Equal Housing Opportunity" in its own artwork,
  // so the adjacent text drops them rather than announcing them twice.
  if (!out.includes("equal-housing-opportunity.svg")) {
    out = out.replace(
      /<p>Equal Housing Opportunity(?: ·|\.) Realtor®\.?<\/p>/,
      '<p class="footer-eho"><img src="/img/equal-housing-opportunity.svg" alt="Equal Housing Opportunity" width="260" height="64" loading="lazy" decoding="async"> <span>Realtor®</span></p>'
    );
  }

  // 404 has no Equal Housing line of its own to swap, so the mark is appended.
  if (!out.includes("equal-housing-opportunity.svg") && file === "404.html") {
    out = out.replace(
      /([ \t]*)<\/div>\n([ \t]*)<\/footer>/,
      `$1  <p class="footer-eho"><img src="/img/equal-housing-opportunity.svg" alt="Equal Housing Opportunity" width="260" height="64" loading="lazy" decoding="async"> <span>Realtor®</span></p>\n$1</div>\n$2</footer>`
    );
  }

  if (!out.includes("equal-housing-opportunity.svg")) {
    log.push(`WARNING: ${file} has no Equal Housing Opportunity line to replace`);
  }
  if (!out.includes('class="footer-legal__links"')) {
    log.push(`WARNING: ${file} has no .footer-legal block for the legal links`);
  }
  return out;
}

/* ----------------------------------------------------------- sitemap */

// lastmod moves only when what a reader sees changes: the visible text of
// <main> (or of <body>, for a page without one) is compared with the last
// commit. A changed or new page gets today; anything else keeps its previous
// date, so a chrome, schema or analytics pass never looks like fresh content.
const visibleText = (html) => {
  const main = /<main\b[^>]*>([\s\S]*?)<\/main>/i.exec(html) || /<body\b[^>]*>([\s\S]*?)<\/body>/i.exec(html);
  return textOf(main ? main[1] : html);
};

const GIT = (() => {
  try {
    execFileSync("git", ["rev-parse", "--verify", "HEAD"], { cwd: ROOT, stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
})();

function committedVersion(file) {
  try {
    return execFileSync("git", ["show", `HEAD:${file.split(sep).join("/")}`], {
      cwd: ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch {
    return null;
  }
}

function buildSitemap(files, pages) {
  const previous = new Map();
  const sitemapPath = join(ROOT, "sitemap.xml");
  if (existsSync(sitemapPath)) {
    for (const m of readFileSync(sitemapPath, "utf8").matchAll(/<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) {
      previous.set(m[1], m[2]);
    }
  }
  const today = new Date().toISOString().slice(0, 10);

  const urls = [];
  let fresh = 0;
  for (const file of files) {
    const html = pages.get(file);
    if (/<meta name="robots" content="[^"]*noindex/i.test(html)) continue;
    const canonical = canonicalOf(html);
    if (!canonical) continue;
    let lastmod = previous.get(canonical) || today;
    if (GIT) {
      const committed = committedVersion(file);
      if (committed === null || visibleText(committed) !== visibleText(html)) lastmod = today;
    }
    if (lastmod === today) fresh += 1;
    urls.push({ loc: canonical, lastmod });
  }
  urls.sort((a, b) => (a.loc === `${SITE}/` ? -1 : b.loc === `${SITE}/` ? 1 : a.loc.localeCompare(b.loc)));

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u.loc}</loc><lastmod>${u.lastmod}</lastmod></url>`).join("\n")}
</urlset>
`;
  writeFileSync(sitemapPath, xml);
  log.push(`sitemap: ${urls.length} URLs, ${fresh} dated ${today}${GIT ? "" : " (no git: dates kept)"}`);
  return urls;
}

/* -------------------------------------------------------------- main */

// The chrome goes first, so every later pass reads pages that already carry
// the current header and footer from scripts/lib/partials.
for (const file of syncChrome()) log.push(`chrome: ${file}`);

const posts = loadPosts();
const published = buildMarketReports(posts);
buildLegal(loadLegal());

const all = htmlFiles();
const files = all.filter((f) => !SKIP.has(f));
const pages = new Map();

// Listing pages are built by the kizlo-listing-site skill with their own
// design, footer and RealEstateListing JSON-LD. Running the site chrome over
// them replaced that schema with the generic agency graph (Procida lost its
// listing markup this way on 2026-08-25), so they are left exactly as written.
const ownsListingSchema = (html) =>
  /<script type="application\/ld\+json">[\s\S]*?"RealEstateListing"[\s\S]*?<\/script>/.test(html) &&
  !html.includes("<!-- schema:start");

// The single-listing sites, their old /listings/ redirect and the internal
// tools are maintained outside the site redesign (lib/chrome.mjs leaves them
// alone for the same reason). Once built they are read, never rewritten:
// a site-wide schema or analytics change does not reach them.
const FROZEN = /^(open-house|studio|3625-waters-edge|8291-procida-isle|listings)\//;

for (const file of files) {
  const original = readFileSync(join(ROOT, file), "utf8");
  if (ownsListingSchema(original) || (FROZEN.test(file) && original.includes(START))) {
    pages.set(file, original);
    continue;
  }
  let html = ensureFooter(file, original);
  html = injectHreflang(file, html);
  html = injectSchema(html, graphFor(file, html, published));
  pages.set(file, html);
  if (html !== original) {
    writeFileSync(join(ROOT, file), html);
    log.push(`schema: ${file}`);
  }
}

// 404 carries no structured data but still needs the legal footer.
if (all.includes("404.html")) {
  const original = readFileSync(join(ROOT, "404.html"), "utf8");
  const html = ensureFooter("404.html", original);
  if (html !== original) {
    writeFileSync(join(ROOT, "404.html"), html);
    log.push("footer: 404.html");
  }
}

// Analytics run over every page, listing pages included, so it happens after
// the schema pass rather than inside it. A frozen page that already carries
// an analytics block is left exactly as written; a new one still gets it.
for (const file of all) {
  if (NO_ANALYTICS.has(file)) continue;
  const original = readFileSync(join(ROOT, file), "utf8");
  if (/<meta http-equiv="refresh"/i.test(original)) continue;
  if (FROZEN.test(file) && original.includes(ANALYTICS_START)) continue;
  const html = injectAnalytics(original);
  if (html !== original) {
    writeFileSync(join(ROOT, file), html);
    log.push(`analytics: ${file}`);
  }
}

buildSitemap(files, pages);

console.log(log.join("\n"));
console.log(`\nbuild ok · ${files.length} pages`);
